// surface layer, 1°×1°, downloaded this session from the same
// official NOAA/NCEI archive as the pH field above.
// ---------------------------------------------------------------
const SALINITY_DATA_URL = "data/salinity_cells.json"; // [[lat, lon, PSU], ...]
const SALINITY_STOPS = [
  [24, [6, 46, 147]],
  [31, [138, 196, 189]],
  [35, [255, 255, 255]],
  [37, [216, 196, 138]],
  [40, [151, 101, 14]],
];
function salinityColor(psu) {
  return rgbToCss(rampColorRGB(psu, SALINITY_STOPS));
}
