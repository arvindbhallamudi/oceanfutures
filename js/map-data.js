// Data provenance, by group:
//  • Warming / SST, real NOAA ERSSTv5 (Extended Reconstructed SST)
//    gridded monthly anomaly data, downloaded from NCEI
//    (www.ncei.noaa.gov/pub/data/cmb/ersst/v5), 2° native resolution
//    resampled to 4°, ocean-masked, anomaly relative to NOAA's own
//    1971-2000 climatology. Bundled as data/sst_cells.json. Scenario
//    steps rescale this real "today" pattern to a target global
//    average anomaly, the same interaction model as Probable
//    Futures' warming-scenario strip.
//  • Sea level, real NOAA tide-gauge long-term trend data (mm/yr),
//    downloaded from tidesandcurrents.noaa.gov/sltrends, 510
//    stations worldwide. Bundled as data/sealevel_stations.json.
//  • Major MPAs, name/authority/area/year curated from Protected
//    Planet (WDPA). Boundaries, where available, are real traced
//    polygons fetched live from OpenStreetMap (via the Overpass
//    API, sourced from each area's own official gazetted boundary
//    relation) and bundled as data/mpa_boundaries.geojson; MPAs not
//    yet mapped in OSM fall back to a representative extent circle
//    sized from their real designated area.
//  • Reef/kelp/mangrove/saltmarsh/tidal-flat points are real,
//    individually-verifiable species occurrence records from GBIF
//    (the Global Biodiversity Information Facility) for each
//    ecosystem's characteristic foundation species (reef-building
//    Scleractinia corals, Laminariales kelp, mangrove genera like
//    Rhizophora/Avicennia, saltmarsh genera like Spartina/Juncus,
//    tidal-flat indicator species like Arenicola marina), thinned to
//    one representative record per ~3° grid cell for even global
//    coverage. Each point's note cites its real GBIF record locality
//    and year — hover/click any marker to see it.
//  • Biodiversity (birds/reptiles/mammals), real species with their
//    current IUCN Red List category, each plotted at multiple real
//    GBIF occurrence records (not single hand-picked coordinates),
//    styled like Ocean Central's risk-of-extinction map.
//  • Shipping, live AIS vessel positions from Digitraffic/Fintraffic
//    (meri.digitraffic.fi), a free, keyless, CORS-open public feed
//    covering the Baltic Sea & Nordic waters, genuinely real-time,
//    not simulated, refreshed on the feed's own ~60s cadence. Plus a
//    reference layer of real, well-documented global trade corridors
//    (IMO/UNCTAD) for context beyond that coverage area.
// ============================================================

